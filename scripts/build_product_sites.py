"""Render the hub, product sites and standalone tools from their source templates."""
import json
from html import escape
from pathlib import Path
from string import Template
from xml.etree import ElementTree

SITE = Path(__file__).resolve().parents[1]
FEATURES = SITE / "src/features"
DOMAINS = SITE / "src/domain"
BASE = "https://rhemahq.com"
GENERATED = "<!-- Generated by scripts/build_product_sites.py. Edit the corresponding source in src/features. -->\n"
THEMES = {"fulfillment": "#101922", "learning": "#f2f1e9", "publishing": "#f3eee5"}
COVERS = {"fulfillment": "night-shift.webp", "learning": "question-index.webp", "publishing": "press-spread.webp"}
DISPLAY_FONTS = {"fulfillment": "barlow-semi-condensed", "learning": "bricolage-grotesque", "publishing": "newsreader"}
TOOLS = {"fulfillment": "ledger", "learning": "moodle"}
DESCRIPTIONS = {
    "fulfillment": "Reconcile 3PL CSV and Excel invoices into a local workbook with fee totals and line-by-line source evidence.",
    "learning": "Merge Moodle question-bank XML, verify categories and question IDs, and download an import file with a source receipt.",
    "publishing": "Prepare PDF, HTML and JATS Publishing 1.2 galleys from an accepted Word manuscript using a local production tool.",
}


def emit(relative, html):
    target = SITE / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(html.replace("<!doctype html>\n", "<!doctype html>\n" + GENERATED, 1),
                      encoding="utf-8", newline="\n")


def render(path, **values):
    return Template(path.read_text(encoding="utf-8")).substitute(values).rstrip()


def offer_links(product, root):
    return {
        **{key: escape(value) for key, value in product.items()},
        "download": root + "tools/" + escape(product["archive"]),
    }


def proof_view():
    formats = json.loads((DOMAINS / "publishing/formats.json").read_text(encoding="utf-8"))
    sample_dir = FEATURES / "publishing/sample"
    samples = "../src/features/publishing/sample"
    article = ElementTree.parse(sample_dir / "production-note.xml")
    metadata = article.find(".//article-meta")
    ElementTree.indent(metadata, space="  ")
    snippet = ElementTree.tostring(metadata, encoding="unicode").strip()
    media = {
        "pdf": f'<img src="{samples}/print-proof.webp" alt="First page of the two-column print galley" '
               'width="1042" height="1474" loading="lazy">',
        "html": f'<iframe src="{samples}/production-note.html" title="HTML galley of the production note" '
                'loading="lazy" sandbox></iframe>',
        "xml": f'<pre tabindex="0"><code>{escape(snippet)}</code></pre>',
    }
    controls, panels = [], []
    for entry in formats:
        id_, label, title, description, file = (escape(entry[key]) for key in ("id", "label", "title", "description", "file"))
        controls.append(f'<button type="button" id="tab-{id_}" aria-controls="proof-{id_}">{label}</button>')
        panels.append(f"""        <section class="galley-format-panel" id="proof-{id_}">
          <div><h3>{title}</h3><p>{description}</p></div>
          <a class="text-link" href="{samples}/{file}" download>Download {label} <span aria-hidden="true">↓</span></a>
          <div class="galley-proof-media">{media[id_]}</div>
        </section>""")
    return {"samples": samples, "format_controls": "\n          " + "\n          ".join(controls) + "\n        ",
            "format_panels": "\n".join(panels)}


def footer(context, products):
    siblings = [f'<a href="../{escape(product["slug"])}/">{escape(product["name"])}</a>'
                for domain, product in products.items() if domain != context]
    links = "".join(siblings)
    return f"""<footer class="product-footer">
  <div class="container">
    <a class="product-hub" href="../"><span aria-hidden="true">←</span> Rhema HQ</a>
    <nav aria-label="Rhema HQ network">{links}<a href="../privacy.html">Privacy</a><a href="../terms.html">Terms</a></nav>
  </div>
</footer>"""


def product_page(context, product, products):
    feature = FEATURES / context
    path = f"../src/features/{context}"
    canonical = BASE + "/" + product["slug"] + "/"
    title = escape(product["name"]) + " — Rhema HQ"
    description = escape(DESCRIPTIONS[context])
    extras = ({"workbench": (feature / "workbench.html").read_text(encoding="utf-8").rstrip()}
              if context in TOOLS else proof_view())
    body = render(feature / "site.html", **offer_links(product, "../"), **extras,
                  art=f"{path}/{COVERS[context]}", footer=footer(context, products))
    bench_style = '\n<link rel="stylesheet" href="../assets/workbench.css">' if context in TOOLS else ""
    if context == "fulfillment":
        bench_style += '\n<link rel="stylesheet" href="../assets/invoice-mapping.css">'
    emit(product["slug"] + "/index.html", f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<link rel="canonical" href="{canonical}">
<meta name="description" content="{description}">
<meta name="theme-color" content="{THEMES[context]}">
<meta property="og:type" content="website">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{description}">
<meta property="og:url" content="{canonical}">
<meta property="og:image" content="{BASE}/src/features/{context}/{COVERS[context]}">
<link rel="preload" href="../assets/fonts/{DISPLAY_FONTS[context]}-latin.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="../assets/base.css">{bench_style}
<link rel="stylesheet" href="../assets/product.css">
<link rel="stylesheet" href="{path}/site.css">
</head>
<body class="product-site {context}-site">
<a class="skip" href="#main">Skip to content</a>
{body}
<script type="module" src="../src/features/product-motion.js"></script>
<script type="module" src="../src/track.js"></script>
</body>
</html>
""")


def hub_offer(product):
    values = offer_links(product, "./")
    if "checkout" in product:
        availability = Template('<p class="price">$price <span>/ $period</span></p>').substitute(values)
        action = Template(
            '<a class="button primary" href="$checkout" data-track="checkout_click" data-product="$sku" '
            'aria-label="Buy $name license">Buy license <span aria-hidden="true">↗</span></a>'
        ).substitute(values)
    else:
        availability = Template("<p>$availability</p>").substitute(values)
        action = Template(
            '<a class="button primary" href="$inquiry" data-track="support_click" data-product="$sku">'
            '$inquiry_label</a>'
        ).substitute(values)
    quote_link = ""
    if "quote_name" in product:
        quote_link = Template(
            '<p><a class="text-link" href="./$slug/#$quote_anchor">Explore $quote_name</a></p>'
        ).substitute(values)
    return Template("""        <article class="purchase-row">
          <div><h3><a href="./$slug/">$name</a></h3>$availability_line$quote_link</div>
          <div class="actions">
            <a class="button" href="$download" download data-track="eval_download" data-product="$sku">$download_label <span aria-hidden="true">↓</span></a>
            $offer_action
          </div>
        </article>""").substitute(values, availability_line=availability, offer_action=action,
                                  quote_link=quote_link)


if __name__ == "__main__":
    products = {path.parent.name: json.loads(path.read_text(encoding="utf-8"))
                for path in sorted(DOMAINS.glob("*/offer.json"))}
    for context, product in products.items():
        product_page(context, product, products)
        if context in TOOLS:
            feature = FEATURES / context
            workbench = (feature / "workbench.html").read_text(encoding="utf-8").rstrip()
            emit(f"tools/{TOOLS[context]}/index.html",
                 render(feature / "tool.html", workbench=workbench, name=escape(product["name"])) + "\n")
    rows = "\n".join(map(hub_offer, products.values()))
    emit("index.html", render(FEATURES / "hub/site.html", product_offers=rows,
                              learning_name=escape(products["learning"]["name"])) + "\n")
    print(f"Emitted the Rhema HQ hub, {len(products)} product sites and {len(TOOLS)} standalone tools.")
